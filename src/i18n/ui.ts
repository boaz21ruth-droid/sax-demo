export type UIKey = keyof (typeof ui)['en'];

export function useTranslations(lang: Locale) {
  return (key: UIKey): string => ui[lang][key] ?? ui[fallbackLocale][key];
}

/** Picks the value for `lang` from a `{ en: …, zh: … }` content field. */
export function pick<T>(field: Record<string, T>, lang: Locale): T {
  return field[lang] ?? field[fallbackLocale];
}
